inline constexpr int GlyphWidth = 5;
inline constexpr int GlyphHeight = 7;
inline constexpr int CellWidth = 6;
inline constexpr int TextHeight = 7;
static_assert(sizeof(Uppercase) + sizeof(Lowercase) == 364, "compact alphabet font must stay 364 bytes");

constexpr const Glyph *glyph(char character) {
    if (character >= 'A' && character <= 'Z') return &Uppercase[character - 'A'];
    if (character >= 'a' && character <= 'z') return &Lowercase[character - 'a'];
    return nullptr;
}

constexpr int textWidth(unsigned int characterCount) {
    return characterCount == 0 ? 0 : (int)characterCount * CellWidth - 1;
}

constexpr int glyphWidth(char character) { return glyph(character) ? CellWidth : 0; }

